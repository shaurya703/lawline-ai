"""Write the numbers the landing page and README quote to frontend/src/lib/facts.json, straight from the result files.

The landing page is static (it must render when the API is offline), so its figures cannot be fetched at run time.
Generating them keeps them from drifting: `tests/test_facts.py` fails when facts.json or the README disagree with
outputs/results.

Run:  python -m lawline.eval.export_facts      (after run_ablation, postprocess and landmark_eval)
"""
from __future__ import annotations
import json
from pathlib import Path
import pandas as pd
from ..config import ROOT, RESULTS_DIR, DATA_PROCESSED, CORPUS_VERSION

FACTS_PATH = ROOT / "frontend" / "src" / "lib" / "facts.json"
ROUTED = "routed: dense (narrative) | faiss+bm25+kg+rerank (question)"
SYSTEMS = [("BM25", "ft", "bm25"), ("Dense, off the shelf (bge-small)", "base", "faiss"), ("Hybrid: dense + BM25 + graph, fused and reranked", "base", "faiss+bm25+kg+rerank"),
           ("Dense, legally fine-tuned", "ft", "faiss"), ("LawLine: fine-tuned + hybrid + routing", "ft", ROUTED)]


def _json(p: Path):
    return json.load(open(p)) if p.exists() else None


def _row(df: pd.DataFrame | None, config: str, task: str = "macro") -> dict | None:
    if df is None:
        return None
    r = df[(df.config == config) & (df.task == task)]
    return None if r.empty else {"r1": round(float(r["R@1"].iloc[0]), 3), "r5": round(float(r["R@5"].iloc[0]), 3), "ndcg": round(float(r["nDCG@10"].iloc[0]), 3)}


def build(results: Path = RESULTS_DIR, processed: Path = DATA_PROCESSED) -> dict:
    csv = lambda p: pd.read_csv(p) if p.exists() else None
    cur = {"ft": csv(results / "ablation_ft/metrics.csv"), "base": csv(results / "ablation_base/metrics.csv")}
    old = {"ft": csv(results / "v1/ablation_ft/metrics.csv"), "base": csv(results / "v1/ablation_base/metrics.csv")}
    stats, old_stats = _json(processed / "corpus_stats.json") or {}, _json(results / "v1/corpus_stats.json") or {}
    detail = _json(processed / "corpus_expansion.json") or {}
    meta = _json(results / "ablation_ft/meta.json") or {}
    lm, lm1 = (_json(results / "landmark_eval.json") or {}).get("summary"), (_json(results / "v1/landmark_eval.json") or {}).get("summary")
    lat = _json(results / "ablation_ft/latency.json") or {}
    ae = _json(results / "answer_eval/summary.json") or {}
    typed = csv(results / "v2_right_type/ablation_ft/metrics.csv")
    ms = lambda k: round(lat[k]["p50_ms"]) if k in lat else None
    facts = {
        "corpus": {"version": CORPUS_VERSION, "documents": stats.get("total"), "provisions": stats.get("statutes"), "judgments": stats.get("cases"), "chunks": meta.get("chunks"),
                   "sc_reports": stats.get("sc_reports"), "hc_judgments": stats.get("hc_judgments"), "key_act_sections": stats.get("key_acts"),
                   "landmarks": (detail.get("sc_reports") or {}).get("landmark_entries_found"), "acts_completed": (detail.get("key_acts") or {}).get("acts_completed"),
                   "acts_added": (detail.get("key_acts") or {}).get("acts_added"), "v1_documents": old_stats.get("total"), "v1_judgments": old_stats.get("cases")},
        "benchmark": {"queries": int(cur["ft"][cur["ft"].task == "macro"]["n"].iloc[0]) if cur["ft"] is not None else None,
                      "systems": [{"system": name, **(_row(cur[enc], cfg) or {}), "v1": _row(old[enc], cfg)} for name, enc, cfg in SYSTEMS],
                      "right_type_r5": (_row(typed, ROUTED) or {}).get("r5")},
        "finetune": {t: {"base": (_row(cur["base"], "faiss", t) or {}).get("r5"), "ft": (_row(cur["ft"], "faiss", t) or {}).get("r5")} for t in ("ipc_facts", "bns_qa")},
        "landmark": None if not lm else {"questions": lm["questions"], "hit5": lm["all_hit@5"], "v1_hit5": (lm1 or {}).get("all_hit@5"), "v1_held": (lm1 or {}).get("judgment_in_corpus")},
        "latency_ms": {"embed": ms("embed_single"), "faiss": ms("faiss"), "bm25": ms("bm25"), "graph": ms("kg"),
                       "rerank": round(lat["rerank_per_pair"]["p50_ms"] * meta.get("top_n", 30)) if "rerank_per_pair" in lat else None},
        "answers": None if "aibe" not in ae else {"corpus": ae.get("corpus", CORPUS_VERSION), "n": ae["aibe"]["n"], "closed_book": round(ae["aibe"]["closed_book_acc"], 3), "with_retrieval": round(ae["aibe"]["rag_acc"], 3),
                                                  "faithfulness": round(ae["rag"]["faithfulness_mean(0-2)"], 2), "gold_cited": round(ae["rag"]["gold_cited_rate"], 2)},
    }
    return facts


START, END = "<!-- results:start (generated by lawline.eval.export_facts) -->", "<!-- results:end -->"


def readme_block(f: dict) -> str:
    """The numeric part of the README's Results section."""
    c, b, lm, lat, an = f["corpus"], f["benchmark"], f["landmark"], f["latency_ms"], f["answers"]
    cell = lambda s, k: f"{s[k]:.3f}" + (f" ({s['v1'][k]:.3f})" if s.get("v1") else "")
    rows = []
    for i, s in enumerate(b["systems"]):
        last = i == len(b["systems"]) - 1
        name = f"**{s['system']}**" if last else s["system"]
        cells = [(f"**{s[k]:.3f}**" + (f" ({s['v1'][k]:.3f})" if s.get("v1") else "")) if last else cell(s, k) for k in ("r1", "r5", "ndcg")]
        rows.append(f"| {name} | " + " | ".join(cells) + " |")
    top = b["systems"][-1]
    out = [START, "",
           f"Benchmark: {b['queries']:,} held-out queries, four tasks (BNS-QA, IPC fact-pattern→section, Constitution-QA, SC case retrieval), document-level metrics, macro-averaged.",
           f"Numbers are for the current corpus ({c['version']}, {c['documents']:,} documents); the first corpus (v1, {c['v1_documents']:,} documents) is in brackets.", "",
           "| System | R@1 | R@5 | nDCG@10 |", "|---|---|---|---|", *rows, "",
           f"The {c['version']} corpus adds {c['sc_reports']:,} Supreme Court judgments (1950–2025), {c['hc_judgments']:,} High Court judgments and {c['key_act_sections']:,} statute sections.",
           "The expansion added no benchmark answer, so the drop from v1 measures distraction: judgments on the same topic now",
           "compete with the section a question is about."]
    if b.get("right_type_r5") is not None:
        out.append(f"Restricting each query to the document type of its answer scores {b['right_type_r5']:.3f} macro R@5, the ceiling for a statute-or-judgment router that is not built.")
    if lm:
        out += ["", f"In exchange the system can cite leading cases. On {lm['questions']} doctrinal questions that each turn on a well-known Supreme Court",
                f"judgment (never named in the question), that judgment is among the first five documents retrieved for {lm['hit5'] * 100:.0f} % of questions,",
                f"against {lm['v1_hit5'] * 100:.0f} % on v1, which held {lm['v1_held']} of the judgments. Every target was added to {c['version']} by name, so this shows that an added judgment",
                "can be found from a plain question; it does not measure how much case law is covered (`lawline/eval/landmark_eval.py`)."]
    ft = f["finetune"]
    out += ["", f"Fine-tuning lifts IPC fact-pattern→section retrieval from {ft['ipc_facts']['base']:.2f} to {ft['ipc_facts']['ft']:.3f} R@5 and BNS-QA from {ft['bns_qa']['base']:.2f} to {ft['bns_qa']['ft']:.2f} on unseen sections."]
    if an:
        note = f" (measured on {an['corpus']}, not re-run on {c['version']})" if an["corpus"] != c["version"] else ""
        out.append(f"Grounding raises AIBE accuracy from {an['closed_book'] * 100:.1f} % to {an['with_retrieval'] * 100:.1f} % (n = {an['n']}) and judged faithfulness to {an['faithfulness']:.1f}/2 with {an['gold_cited'] * 100:.0f} % of answers citing the gold provision{note}.")
    out += [f"Retrieval latency on a laptop (median): embed {lat['embed']} ms · FAISS {lat['faiss']} ms · BM25 {lat['bm25']} ms · KG {lat['graph']} ms · reranker ≈ {lat['rerank'] / 1000:.2f} s.", "", END]
    return "\n".join(out)


def update_readme(f: dict, readme: Path = ROOT / "README.md") -> bool:
    s = readme.read_text()
    if START not in s or END not in s:
        return False
    a, b = s.index(START), s.index(END) + len(END)
    readme.write_text(s[:a] + readme_block(f) + s[b:])
    return True


def main():
    facts = build()
    FACTS_PATH.write_text(json.dumps(facts, indent=2) + "\n")
    print(json.dumps(facts, indent=2))
    print("README results block", "updated" if update_readme(facts) else "not found (no markers)")


if __name__ == "__main__":
    main()
